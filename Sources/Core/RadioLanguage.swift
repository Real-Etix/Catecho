import Foundation

enum RadioLanguage: String, CaseIterable {
    case system, english = "en", simplified = "zh-Hans", traditional = "zh-Hant"
    func resolved(preferred: [String] = Locale.preferredLanguages) -> RadioLanguage {
        guard self == .system else { return self }
        for identifier in preferred {
            let parts = identifier.lowercased().replacingOccurrences(of: "_", with: "-").split(separator: "-").map(String.init)
            if parts.first == "en" { return .english }
            if parts.first == "zh" {
                if parts.contains("hant") { return .traditional }
                if parts.contains("hans") { return .simplified }
                return parts.contains(where: { ["tw", "hk", "mo"].contains($0) }) ? .traditional : .simplified
            }
        }
        return .english
    }
    var nativeName: String {
        switch self { case .system: return "System default"; case .english: return "English"; case .simplified: return "简体中文"; case .traditional: return "繁體中文" }
    }
    var locale: Locale { Locale(identifier: resolved().rawValue) }
    func text(_ key: String) -> String {
        let language = resolved()
        guard language != .english else { return key }
        if let value = Self.strings[key] { return language == .simplified ? value.0 : value.1 }
        // Localize known diagnostic fragments while preserving source names and technical details.
        return Self.diagnosticFragments.reduce(key) { value, fragment in
            guard let translated = Self.strings[fragment] else { return value }
            return value.replacingOccurrences(of: fragment, with: language == .simplified ? translated.0 : translated.1)
        }
    }
    func metric(_ original: String) -> String {
        switch resolved() {
        case .simplified: return text(original).replacingOccurrences(of: " total stars", with: " 颗星").replacingOccurrences(of: " stars today", with: " 今日新增星标").replacingOccurrences(of: " stars this week", with: " 本周新增星标").replacingOccurrences(of: " stars this month", with: " 本月新增星标")
        case .traditional: return text(original).replacingOccurrences(of: " total stars", with: " 顆星").replacingOccurrences(of: " stars today", with: " 今日新增星標").replacingOccurrences(of: " stars this week", with: " 本週新增星標").replacingOccurrences(of: " stars this month", with: " 本月新增星標")
        default: return original
        }
    }
